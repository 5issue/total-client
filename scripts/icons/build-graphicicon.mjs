import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { svgFileToJsx, renderFnCode } from './svg-to-tsx.mjs';

const SVG_DIR = path.resolve('src/components/atoms/GraphicIcon/svg');
const OUT = path.resolve('src/components/atoms/GraphicIcon/graphic-icons.generated.tsx');

const files = readdirSync(SVG_DIR)
  .filter((f) => f.endsWith('.svg'))
  .sort();

const entries = [];
const fnCodes = [];

for (const file of files) {
  const name = path.basename(file, '.svg');
  const jsx = await svgFileToJsx(path.join(SVG_DIR, file));
  const fnName = `render_${name.replace(/-/g, '_')}`;
  fnCodes.push(renderFnCode(fnName, jsx));
  entries.push({ name, viewBox: jsx.viewBox, themable: jsx.themable, fnName });
}

const unionBody = entries.map((e) => `'${e.name}'`).join(' | ');

const registryEntries = entries
  .map((e) => {
    const keyLiteral = /^[a-zA-Z_$][\w$]*$/.test(e.name) ? e.name : `'${e.name}'`;
    return `  ${keyLiteral}: { viewBox: '${e.viewBox}', themable: ${e.themable}, render: (idFor) => ${e.fnName}(idFor) },`;
  })
  .join('\n');

const out = `// AUTO-GENERATED by scripts/icons (svgr 기반) — do not hand-edit.
// 소스: src/components/atoms/GraphicIcon/svg/*.svg (issue #11).
// 재생성: npm run icons:build
import type { ReactNode } from 'react';

export type GraphicIconName = ${unionBody};

type GraphicIconVariant = {
  viewBox: string;
  themable: boolean;
  render: (idFor: (raw: string) => string) => ReactNode;
};

${fnCodes.join('\n\n')}

export const GRAPHIC_ICONS: Record<GraphicIconName, GraphicIconVariant> = {
${registryEntries}
};
`;

writeFileSync(OUT, out);
console.log(`GraphicIcon: ${entries.length}개 -> ${OUT}`);
