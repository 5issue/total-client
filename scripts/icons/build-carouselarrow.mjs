import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { svgFileToJsx, renderFnCode } from './svg-to-tsx.mjs';

const SVG_DIR = path.resolve('src/components/atoms/CarouselArrow/svg');
const OUT = path.resolve('src/components/atoms/CarouselArrow/carousel-arrow-icons.generated.tsx');

const files = readdirSync(SVG_DIR)
  .filter((f) => f.endsWith('.svg'))
  .sort();

const byVariant = { outline: {}, filled: {} };
const fnCodes = [];

for (const file of files) {
  const base = path.basename(file, '.svg');
  const match = base.match(/^(outline|filled)-(left|right)$/);
  if (!match) {
    console.warn(`이름 규칙 불일치, 건너뜀: ${file}`);
    continue;
  }
  const [, variant, direction] = match;
  const jsx = await svgFileToJsx(path.join(SVG_DIR, file));
  const fnName = `render_${variant}_${direction}`;
  fnCodes.push(renderFnCode(fnName, jsx));
  byVariant[variant][direction] = { viewBox: jsx.viewBox, fnName };
}

const out = `// AUTO-GENERATED by scripts/icons (svgr 기반) — do not hand-edit.
// 소스: src/components/atoms/CarouselArrow/svg/*.svg (Figma "Icon_Arrow" 컴포넌트셋, issue #11).
// 재생성: npm run icons:build
import type { ReactNode } from 'react';

export type CarouselArrowVariant = 'outline' | 'filled';
export type CarouselArrowDirection = 'left' | 'right';

type Def = {
  viewBox: string;
  render: (idFor: (raw: string) => string) => ReactNode;
};

${fnCodes.join('\n\n')}

export const CAROUSEL_ARROWS: Record<CarouselArrowVariant, Record<CarouselArrowDirection, Def>> = {
  outline: {
    left: { viewBox: '${byVariant.outline.left.viewBox}', render: (idFor) => ${byVariant.outline.left.fnName}(idFor) },
    right: { viewBox: '${byVariant.outline.right.viewBox}', render: (idFor) => ${byVariant.outline.right.fnName}(idFor) },
  },
  filled: {
    left: { viewBox: '${byVariant.filled.left.viewBox}', render: (idFor) => ${byVariant.filled.left.fnName}(idFor) },
    right: { viewBox: '${byVariant.filled.right.viewBox}', render: (idFor) => ${byVariant.filled.right.fnName}(idFor) },
  },
};
`;

writeFileSync(OUT, out);
console.log(`CarouselArrow: 4개 -> ${OUT}`);
